// Ensures ~/.browser-bays/config.json and the bay's profile exist, applies the
// bay's colour where the driver supports it, and prints the command line of the
// bay's driver (the MCP server that runs its browser), one argument per line.
//
// A driver is a template: `command` and `args`, where {profile}, {name},
// {emoji} and {color} are filled in, `headlessArgs` added when the bay is
// headless, `theme` naming how the colour is applied ("chrome" or none), and
// `process` the text that identifies the browser's main process (for Focus).
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

export const DEFAULT_DRIVERS = {
  'chrome-devtools': {
    label: 'Chrome (chrome-devtools-mcp)',
    command: 'npx',
    args: ['-y', 'chrome-devtools-mcp@latest', '--userDataDir', '{profile}', '--chromeArg=--window-name={emoji} {name}'],
    headlessArgs: ['--headless'],
    theme: 'chrome',
    process: '--user-data-dir={profile}',
  },
  'firefox-devtools': {
    label: 'Firefox (firefox-devtools-mcp)',
    command: 'npx',
    args: ['-y', '@mozilla/firefox-devtools-mcp@latest', '--profilePath', '{profile}', '--toolPreset', 'developer'],
    headlessArgs: ['--headless'],
    theme: null,
    process: '{profile}',
  },
}

export const DEFAULT_CONFIG = {
  autoAssign: true,
  holdServers: [],
  drivers: DEFAULT_DRIVERS,
  bays: [
    { id: 'bay-1', name: 'red', color: '#E5484D', emoji: '🔴', headless: false, driver: 'chrome-devtools' },
    { id: 'bay-2', name: 'blue', color: '#0090FF', emoji: '🔵', headless: false, driver: 'chrome-devtools' },
    { id: 'bay-3', name: 'green', color: '#30A46C', emoji: '🟢', headless: false, driver: 'chrome-devtools' },
    { id: 'bay-4', name: 'amber', color: '#FFB224', emoji: '🟠', headless: false, driver: 'chrome-devtools' },
  ],
}

const [bayId, home] = process.argv.slice(2)
const configPath = join(home, 'config.json')
if (!existsSync(configPath)) {
  mkdirSync(home, { recursive: true })
  writeFileSync(configPath, JSON.stringify(DEFAULT_CONFIG, null, 2) + '\n')
}
const raw = JSON.parse(readFileSync(configPath, 'utf8'))
const drivers = { ...DEFAULT_DRIVERS, ...(raw.drivers ?? {}) }
const bays = Array.isArray(raw.bays) && raw.bays.length ? raw.bays : DEFAULT_CONFIG.bays
const bay = bays.find(b => b.id === bayId) ?? DEFAULT_CONFIG.bays.find(b => b.id === bayId)
if (!bay) {
  console.error(`browser-bays: no bay ${bayId} in ${configPath}`)
  process.exit(64)
}
const driverName = bay.driver ?? 'chrome-devtools'
const driver = drivers[driverName]
if (!driver) {
  console.error(`browser-bays: bay ${bay.name} names driver "${driverName}", which config.json does not define`)
  process.exit(64)
}

// Bay red keeps its original Chrome profile path; other drivers get their own.
export function profileOf(b, d) {
  return d === 'chrome-devtools' ? join(home, 'profiles', b.id) : join(home, 'profiles', `${b.id}-${d}`)
}
const profile = profileOf(bay, driverName)
mkdirSync(profile, { recursive: true })

const fill = s =>
  String(s)
    .replaceAll('{profile}', profile)
    .replaceAll('{name}', bay.name ?? bay.id)
    .replaceAll('{emoji}', bay.emoji ?? '')
    .replaceAll('{color}', bay.color ?? '')

function running() {
  try {
    const ps = execFileSync('ps', ['-axo', 'command='], { encoding: 'utf8' })
    return ps.split('\n').some(l => l.includes(fill(driver.process ?? '{profile}')))
  } catch {
    return false
  }
}

function argb(hex) {
  const n = parseInt(hex.replace('#', ''), 16)
  return ((0xff << 24) | n) | 0 // signed 32-bit, as Chrome stores SkColor
}

if (driver.theme === 'chrome' && bay.color && !running()) {
  mkdirSync(join(profile, 'Default'), { recursive: true })
  const prefsPath = join(profile, 'Default', 'Preferences')
  let prefs = {}
  try { prefs = JSON.parse(readFileSync(prefsPath, 'utf8')) } catch {}
  const color = argb(bay.color)
  prefs.browser = { ...prefs.browser, theme: { ...prefs.browser?.theme, user_color: color, color_variant: 1, is_grayscale: false } }
  prefs.autogenerated = { ...prefs.autogenerated, theme: { ...prefs.autogenerated?.theme, color } }
  prefs.extensions = { ...prefs.extensions, theme: { ...prefs.extensions?.theme, id: 'autogenerated_theme_id' } }
  writeFileSync(prefsPath, JSON.stringify(prefs))
}

const argv = [driver.command, ...(driver.args ?? []).map(fill), ...(bay.headless ? (driver.headlessArgs ?? []).map(fill) : [])]
process.stdout.write(argv.join('\n') + '\n')
